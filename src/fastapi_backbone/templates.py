"""Versioned source templates used by the project generator."""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True, slots=True)
class TemplateFile:
    path: str
    content: str


def render_default_template(package: str, project_name: str) -> tuple[TemplateFile, ...]:
    """Return the current template set through a stable rendering API."""
    return (
        TemplateFile(f"src/{package}/__init__.py", '"""Generated FastAPI application."""\n'),
        TemplateFile(
            f"src/{package}/app.py",
            f'''"""Application composition root."""\n\nfrom fastapi import FastAPI\n\n\ndef create_app() -> FastAPI:\n    app = FastAPI(title="{package}")\n\n    @app.get("/api/health/live")\n    async def live() -> dict[str, str]:\n        return {{"status": "ok"}}\n\n    return app\n''',
        ),
        TemplateFile(
            "tests/test_app.py",
            f'''from {package}.app import create_app\n\n\ndef test_application_factory() -> None:\n    app = create_app()\n    assert app.title == "{package}"\n''',
        ),
        TemplateFile(
            ".env.example",
            "ENVIRONMENT=development\nDATABASE_URL=sqlite+aiosqlite:///./app.db\nAI_ENABLED=false\nAI_MODEL=\n",
        ),
        TemplateFile(
            ".gitignore",
            ".venv/\n__pycache__/\n.pytest_cache/\n.ruff_cache/\n.mypy_cache/\n.env\n*.db\n",
        ),
        TemplateFile(
            "README.md",
            f'''# {project_name}\n\nGenerated by FastAPI Backbone.\n\nThe application factory is `{package}.app:create_app`.\n''',
        ),
    )
